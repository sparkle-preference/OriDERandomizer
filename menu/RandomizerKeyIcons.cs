    // Caps whose name is not a KeyCode, or that stand for more than one.
    private static readonly string[][] Also = {
        new[] { "Alt", "LeftAlt", "RightAlt" },
        new[] { "Comma", "Less" },
        new[] { "Period", "Greater" },
        new[] { "Semicolon", "Colon" },
