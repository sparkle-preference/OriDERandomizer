// Key caps the game's icon font never had, borrowed from Ori's sequel and worked over to sit
// beside the ones it does have.
//
// That font is two objects and you need both. The generator is a list of character to prefab,
// and the <icon> style carries a BitmapFont whose entry per character is what the text layout
// leaves room for; a character missing from the font is swapped for the missing-glyph box
// before it ever reaches the renderer. Its ascii table has no room for fifty more caps, but
// `otherChars` is an empty array searched by id, so the caps live in the private use area and
// nobody has to ration letters.
public static class RandomizerKeyIcons {
    private class Cap {
        public Cap(string name, int x, int y, int width, int height) {
            Name = name;
            X = x;
            Y = y;
            Width = width;
            Height = height;
        }

        public readonly string Name;

        public readonly int X;

        public readonly int Y;

        public readonly int Width;

        public readonly int Height;

        public char Character;

        // what to put in a message to draw it, once it has one
        public string Icon;

        // room for it on a line, worked out against a cap the font already has
        public float Advance = 1f;
    }

